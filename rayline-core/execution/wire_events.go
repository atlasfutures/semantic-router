// Wire inference is the primary v2 event source: harnesses are unmodified, so
// the core reads only what they already send. Literals are positive matches on
// text a harness itself writes, captured from real traffic: the Claude Code and
// Codex literals are VSR's (pkg/selection/raylinearc/policy_turn_signals.go,
// ported from pathfinder's collection rules); the typed-prompt rule is
// pathfinder's curation/workshop_turns.typed_text; the Pi literals are Pi
// 0.80.2's (dist/core/messages.js, compaction/utils.js). Anything unmatched is
// unknown, never promoted to a boundary.

const (
	piCompactionPrefix    = "The conversation history before this point was compacted into the following summary:"
	piBranchSummaryPrefix = "The following is a summary of a branch that this conversation came back from:"
	piSummarizationSystem = "You are a context summarization assistant. Your task is to read a conversation between a user and an AI assistant, then produce a structured summary following the exact format specified."

	claudeCodeContinuation = "This session is being continued from a previous conversation that ran out of context."
	claudeCodeSummarize    = "CRITICAL: Respond with TEXT ONLY. Do NOT call any tools.\n\n- Do NOT use Read, Bash, Grep, Glob, Edit, Write, or ANY other tool."
	claudeCodeSuggestion   = "[SUGGESTION MODE: Suggest what the user might naturally type next into Claude Code.]"
	claudeCodeTitle        = "You are naming a coding session so the user can pick it out of a long list of sessions."
	claudeCodeBilling      = "x-anthropic-billing-header:"

	codexSummaryPrefix = "Another language model started to solve this problem and produced a summary " +
		"of its thinking process. You also have access to the state of the tools that " +
		"were used by that language model. Use this to build on the work that has " +
		"already been done and avoid duplicating work. Here is the summary produced by " +
		"the other language model, use the information in this summary to assist with " +
		"your own analysis:\n"
	codexCompactionPrompt = "You are performing a CONTEXT CHECKPOINT COMPACTION. Create a handoff summary " +
		"for another LLM that will resume the task.\n\nInclude:\n- Current progress and " +
		"key decisions made\n- Important context, constraints, or user preferences\n- " +
		"What remains to be done (clear next steps)\n- Any critical data, examples, or " +
		"references needed to continue\n\nBe concise, structured, and focused on helping " +
		"the next LLM seamlessly continue the work.\n"
)

var (
	reminderBlock = regexp.MustCompile(`(?s)<system-reminder>.*?</system-reminder>`)
	projectBlock  = regexp.MustCompile(`(?s)<project_context>.*?</project_context>`)
	// notTyped are harness-authored user turns (pathfinder NOT_TYPED, plus the
	// Pi and Codex summary preambles): never a user decision point.
	notTyped = []string{"<command-message>", "<command-name>", "<local-command-stdout>", "[Request interrupted by user",
		"This session is being continued from a previous conversation",
		"Caveat: The messages below were generated by the user while running local commands",
		"Your task is to create a detailed summary of the conversation so far",
		piCompactionPrefix, piBranchSummaryPrefix, codexSummaryPrefix,
		// Codex writes its environment as its own user message (0.154.0).
		"<environment_context>"}
)

// wireMessage is one client wire message (Responses: one input item), indexed
// exactly as wireMessageRoles and wireMessageFingerprints index them.
type wireMessage struct {
	role       string
	texts      []string // text blocks, in order, before any tool result
	allTexts   []string // every text block, in order
	toolResult bool
	toolCalls  []string
	modelItem  bool // Responses model output (reasoning, function calls)
}

type wireRequest struct {
	system   []string
	messages []wireMessage
}

func parseWireRequest(format llmprotocol.WireFormat, body []byte) wireRequest {
	var result wireRequest
	var wire map[string]json.RawMessage
	if json.Unmarshal(body, &wire) != nil {
		return result
	}
	switch format {
	case llmprotocol.OpenAIResponsesV1:
		result.system = stringsOf(wire["instructions"])
		var input []json.RawMessage
		if json.Unmarshal(wire["input"], &input) != nil {
			var whole string
			if json.Unmarshal(wire["input"], &whole) == nil {
				result.messages = []wireMessage{{role: "user", texts: []string{whole}}}
			}
			return result
		}
		for _, raw := range input {
			var item struct {
				Type    string          `json:"type"`
				Role    string          `json:"role"`
				Name    string          `json:"name"`
				Content json.RawMessage `json:"content"`
			}
			_ = json.Unmarshal(raw, &item)
			message := wireMessage{role: item.Role}
			switch item.Type {
			case "function_call", "custom_tool_call":
				message = wireMessage{role: "assistant", toolCalls: []string{item.Name}, modelItem: true}
			case "reasoning":
				message = wireMessage{role: "assistant", modelItem: true}
			case "function_call_output", "custom_tool_call_output":
				message = wireMessage{role: "tool", toolResult: true, modelItem: true}
			default:
				message.texts = stringsOf(item.Content)
				message.allTexts = message.texts
			}
			result.messages = append(result.messages, message)
		}
	default:
		result.system = stringsOf(wire["system"])
		var messages []struct {
			Role      string          `json:"role"`
			Content   json.RawMessage `json:"content"`
			ToolCalls []struct {
				Function struct {
					Name string `json:"name"`
				} `json:"function"`
			} `json:"tool_calls"`
		}
		_ = json.Unmarshal(wire["messages"], &messages)
		for _, raw := range messages {
			if isSystemRole(raw.Role) {
				// Chat carries its system prompt as a message.
				result.system = append(result.system, stringsOf(raw.Content)...)
			}
			message := wireMessage{role: raw.Role, toolResult: raw.Role == "tool"}
			for _, call := range raw.ToolCalls {
				message.toolCalls = append(message.toolCalls, call.Function.Name)
			}
			var whole string
			if json.Unmarshal(raw.Content, &whole) == nil {
				if !message.toolResult {
					message.texts = []string{whole}
					message.allTexts = message.texts
				}
			} else {
				var blocks []struct {
					Type string  `json:"type"`
					Text *string `json:"text"`
					Name string  `json:"name"`
				}
				_ = json.Unmarshal(raw.Content, &blocks)
				for _, block := range blocks {
					switch block.Type {
					case "tool_result":
						message.toolResult = true
					case "tool_use":
						message.toolCalls = append(message.toolCalls, block.Name)
					case "text", "input_text", "output_text":
						if block.Text != nil {
							message.allTexts = append(message.allTexts, *block.Text)
							if !message.toolResult {
								message.texts = append(message.texts, *block.Text)
							}
						}
					}
				}
			}
			result.messages = append(result.messages, message)
		}
	}
	return result
}

// stringsOf reads a string, or the text of each block of a block list.
func stringsOf(raw json.RawMessage) []string {
	var whole string
	if json.Unmarshal(raw, &whole) == nil {
		return []string{whole}
	}
	var blocks []json.RawMessage
	if json.Unmarshal(raw, &blocks) != nil {
		return nil
	}
	var result []string
	for _, block := range blocks {
		var text string
		if json.Unmarshal(block, &text) == nil {
			result = append(result, text)
			continue
		}
		var typed struct {
			Text *string `json:"text"`
		}
		if json.Unmarshal(block, &typed) == nil && typed.Text != nil {
			result = append(result, *typed.Text)
		}
	}
	return result
}

// typedText is the user's own words: text before any tool result, with
// reminders and project context removed; empty for a harness-authored turn.
func (message wireMessage) typedText() string {
	if message.role != "user" {
		return ""
	}
	typed := strings.Join(message.texts, "\n")
	typed = strings.TrimSpace(projectBlock.ReplaceAllString(reminderBlock.ReplaceAllString(typed, ""), ""))
	for _, prefix := range notTyped {
		if strings.HasPrefix(typed, prefix) {
			return ""
		}
	}
	return typed
}

// firstText is the first text block that is not an injected reminder.
func (message wireMessage) firstText() string {
	for _, text := range message.texts {
		trimmed := strings.TrimLeftFunc(text, unicode.IsSpace)
		if !strings.HasPrefix(trimmed, "<system-reminder>") {
			return trimmed
		}
	}
	return ""
}

func (message wireMessage) lastText() string {
	if len(message.allTexts) == 0 {
		return ""
	}
	return message.allTexts[len(message.allTexts)-1]
}

func isSystemRole(role string) bool { return role == "system" || role == "developer" }

// lastNonSystem is the index of the last message that is not a trailing
// system/developer message, or -1.
func (request wireRequest) lastNonSystem() int {
	index := len(request.messages) - 1
	for index >= 0 && isSystemRole(request.messages[index].role) {
		index--
	}
	return index
}

func (request wireRequest) firstNonSystem() int {
	for index, message := range request.messages {
		if !isSystemRole(message.role) {
			return index
		}
	}
	return -1
}

func (request wireRequest) hasAssistant() bool {
	for _, message := range request.messages {
		if message.role == "assistant" {
			return true
		}
	}
	return false
}

// isSidecall recognizes a harness's own auxiliary calls: summarization for a
// compaction, title and prompt-suggestion calls. They never advance a branch.
func (request wireRequest) isSidecall() bool {
	for _, text := range request.system {
		if strings.HasPrefix(text, piSummarizationSystem) || strings.HasPrefix(text, claudeCodeTitle) {
			return true
		}
	}
	last := request.lastNonSystem()
	if last < 0 || request.messages[last].role != "user" {
		return false
	}
	text := request.messages[last].lastText()
	return strings.HasPrefix(text, claudeCodeSummarize) || strings.HasPrefix(text, claudeCodeSuggestion) || text == codexCompactionPrompt
}

// claudeCodeSubagent is Claude Code's own cc_is_subagent=true billing claim.
func (request wireRequest) claudeCodeSubagent() bool {
	for _, text := range request.system {
		if !strings.HasPrefix(text, claudeCodeBilling) {
			continue
		}
		for _, field := range strings.Split(text[len(claudeCodeBilling):], ";") {
			key, value, _ := strings.Cut(field, "=")
			if strings.TrimSpace(key) == "cc_is_subagent" {
				return strings.EqualFold(strings.TrimSpace(value), "true")
			}
		}
	}
	return false
}

// summaryMarker is the index of a harness-written compaction summary, or -1:
// Pi and Claude Code open the first message with it; Codex ends the leading
// run of user messages (before any model output) with it.
func (request wireRequest) summaryMarker() int {
	if first := request.firstNonSystem(); first >= 0 && request.messages[first].role == "user" {
		text := request.messages[first].firstText()
		if strings.HasPrefix(text, piCompactionPrefix) || strings.HasPrefix(text, claudeCodeContinuation) {
			return first
		}
	}
	summary := -1
	for index, message := range request.messages {
		if message.modelItem || message.role == "assistant" {
			break
		}
		if message.role == "user" && strings.HasPrefix(message.firstText(), codexSummaryPrefix) {
			summary = index
		}
	}
	return summary
}

// inferV2Event is the v2 event from the wire alone: a harness side call, a
// compaction detected against the previous request (only when this request
// rewrites the prefix), else the trailing turn.
func inferV2Event(request wireRequest, previous, current []string, rewrite, lineage bool) ExecutionEvent {
	if request.isSidecall() {
		kind := EventSidecall
		return ExecutionEvent{Kind: &kind, Basis: BasisMarkerInferred}
	}
	if rewrite {
		if compaction := detectCompaction(request, previous, current); compaction != nil {
			kind := EventCompaction
			return ExecutionEvent{Kind: &kind, Basis: BasisMarkerInferred, Compaction: compaction}
		}
	}
	return inferWireEvent(request, lineage)
}

// inferWireEvent reads the trailing turn. It is called only when no
// compaction was detected. lineage reports a new branch of a session that
// already has another branch (a child session or subagent).
func inferWireEvent(request wireRequest, lineage bool) ExecutionEvent {
	kind := func(value string) ExecutionEvent { return ExecutionEvent{Kind: &value, Basis: BasisMarkerInferred} }
	if request.isSidecall() {
		return kind(EventSidecall)
	}
	if !request.hasAssistant() {
		if request.claudeCodeSubagent() || lineage {
			return kind(EventSubagentStart)
		}
		return kind(EventTaskStart)
	}
	last := request.lastNonSystem()
	if last < 0 {
		return ExecutionEvent{Basis: BasisUnknown}
	}
	message := request.messages[last]
	switch message.role {
	case "tool":
		return kind(EventToolResult)
	case "user":
		// A subagent's report can arrive as plain user text after its call:
		// tool output, never a typed turn (pathfinder SUBAGENT_CALL).
		if !message.toolResult && last > 0 {
			calls := request.messages[last-1].toolCalls
			if len(calls) > 0 && (calls[len(calls)-1] == "Agent" || calls[len(calls)-1] == "Task") {
				return kind(EventToolResult)
			}
		}
		if message.typedText() != "" {
			return kind(EventUserMessage)
		}
		if message.toolResult {
			return kind(EventToolResult)
		}
	}
	return ExecutionEvent{Basis: BasisUnknown}
}

// retainedRun aligns the longest contiguous run of current, starting after
// first, that equals the end of previous. It returns the run's start and length.
func retainedRun(previous, current []string, first int) (int, int) {
	bestStart, bestLength := -1, 0
	for start := first + 1; start < len(current); start++ {
		for length := min(len(previous), len(current)-start); length > bestLength; length-- {
			matched := true
			for offset := 0; offset < length; offset++ {
				if previous[len(previous)-length+offset] != current[start+offset] {
					matched = false
					break
				}
			}
			if matched {
				bestStart, bestLength = start, length
				break
			}
		}
	}
	return bestStart, bestLength
}

// detectCompaction compares a prefix-rewriting request with the last request
// the core saw on this branch. It is a compaction when a harness summary
// marker opens the transcript, or when a new user message replaces at least
// two earlier messages and is followed by a retained run matching the end of
// the previous request. Any other rewrite is a new epoch with no boundary.
func detectCompaction(request wireRequest, previous, current []string) *CompactionEvent {
	first := request.firstNonSystem()
	if first < 0 || len(previous) == 0 {
		return nil
	}
	start, run := retainedRun(previous, current, first)
	if summary := request.summaryMarker(); summary >= 0 {
		// A summary the previous request already carried is not a new
		// compaction: any other rewrite after it is a new epoch, no boundary.
		for _, seen := range previous {
			if seen == current[summary] {
				return nil
			}
		}
		event := &CompactionEvent{SummaryMessage: summary, New: true}
		if run > 0 && start == summary+1 {
			event.RetainedFrom = &start
		}
		return event
	}
	if run == 0 || start != first+1 || request.messages[first].role != "user" || len(previous)-run < 2 {
		return nil
	}
	for _, seen := range previous {
		if seen == current[first] {
			return nil
		}
	}
	return &CompactionEvent{SummaryMessage: first, RetainedFrom: &start, New: true}
}
